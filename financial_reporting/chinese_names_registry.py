def clean_str(s: str) -> str:
    s = re.sub(r'[\\/*?:"<>|]', "", s)
    s = s.replace("&", "与").replace(" ", "_").replace(".", "").replace("-", "_")
    return s.strip("_")


def get_standard_company_chinese_name(comp: dict) -> str:
    """获取标的的标准中文公司名称 (杜绝纯英文代码或纯字母，保障美股与日股 100% 中文可读)."""
    mkt = comp.get("market", "US")
    ticker = comp.get("ticker", "").split(":")[-1].upper()
    name_zh = comp.get("name_zh", "").strip()
    name_en = comp.get("name", "").strip()

    if mkt == "JP":
        if ticker in JP_TICKER_TO_CHINESE:
            return JP_TICKER_TO_CHINESE[ticker]
        if name_zh and not name_zh.isascii():
            return clean_str(name_zh)
        return clean_str(name_en) or ticker
    else:
        # 美股
        if ticker in US_TICKER_TO_CHINESE:
            return US_TICKER_TO_CHINESE[ticker]
        if name_zh and not name_zh.isascii() and len(name_zh) > 1:
            return clean_str(name_zh)
        
        # 英文名称启发式规则，保障 100% 中文名称输出
        clean_en = name_en.replace("Corporation", "公司").replace("Corp.", "公司").replace("Inc.", "公司")
        clean_en = clean_en.replace("Company", "公司").replace("Group", "集团").replace("Holdings", "控股")
        clean_en = clean_en.replace("Technologies", "科技").replace("Technology", "科技")
        clean_en = clean_en.replace("Pharmaceuticals", "制药").replace("Pharma", "制药")
        clean_en = clean_en.replace("Energy", "能源").replace("Financial", "金融")
        clean_en = clean_en.replace("Enterprises", "企业").replace("International", "国际")
        return clean_str(clean_en) or f"{ticker}公司"


def get_dossier_filename(comp: dict) -> str:
    """生成符合用户严格要求的规范文件名: 【代码】_【中文名称】.pdf"""
    ticker = comp.get("ticker", "").split(":")[-1].upper()
    cn_name = get_standard_company_chinese_name(comp)
    return f"{ticker}_{cn_name}.pdf"
