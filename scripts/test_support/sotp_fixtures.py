def make_sotp_test_analyzer(test):
    """生成原文字节、字段引用、独立假设和冻结行情，全部位于项目临时目录。"""
    area = project_temp(test, "sotp-contract-")
    source = area / "filing.synthetic.txt"
    source.write_text("SYNTHETIC TEST INPUT ONLY\n" + json.dumps(SYNTHETIC_PROFILES), encoding="utf-8")
    reference = {"source_path": source.name, "sha256": hashlib.sha256(source.read_bytes()).hexdigest(),
                 "locator": "synthetic fixture fields"}
    profiles = {}
    for ticker, old in SYNTHETIC_PROFILES.items():
        facts = {key: old[key] for key in ("company_name", "fiscal_year", "total_revenue",
                 "total_operating_income", "effective_tax_rate", "diluted_shares")}
        facts.update(financial_unit="usd_million", shares_unit="million_shares",
                     unallocated_operating_income=old["total_operating_income"] - sum(s["operating_income"] for s in old["segments"]))
        facts["segments"] = [{key: segment[key] for key in ("segment_id", "name_zh", "name_en", "revenue", "operating_income")}
                             for segment in old["segments"]]
        fields = ["total_revenue", "total_operating_income", "effective_tax_rate", "diluted_shares", "unallocated_operating_income"]
        fields += [f"segments.{segment['segment_id']}.{name}" for segment in old["segments"]
                   for name in ("revenue", "operating_income")]
        profiles[ticker] = {
            "data_origin": "synthetic", "facts": facts,
            "fact_evidence": {key: dict(reference) for key in fields},
            "assumptions": {"assumption_id": "synthetic-scenario-v1", "rationale": "合成情景回归使用",
                            "calibration_status": "uncalibrated_scenario",
                            "segments": {segment["segment_id"]: {key: segment[key] for key in
                                         ("cost_pass_through_power", "inventory_buffer_days", "relevant_keywords")}
                                         for segment in old["segments"]}},
            "quote": {"price": old["current_share_price"], "timestamp": "2026-10-16T14:00:00Z",
                      "market": "US", "currency": "USD", "source": dict(reference)},
        }
    registry = area / "profiles.json"
    registry.write_text(json.dumps({"schema_version": "1.0.0", "profiles": profiles}), encoding="utf-8")
    return SotpEventAnalyzer(root_dir=area, profiles_path=registry.name, db_path="events.sqlite3",
                             allow_synthetic=True, current_time_iso="2026-10-16T14:05:00Z")
